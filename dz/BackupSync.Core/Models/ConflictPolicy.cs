namespace BackupSync.Core.Models
{
    /// <summary>
    /// Политика разрешения конфликтов синхронизации.
    /// Определяет действие, если файл существует и в Источнике (Source), и в Назначении (Dest), но их метаданные отличаются.
    /// </summary>
    public enum ConflictPolicy
    {
        /// <summary>
        /// Спрашивать пользователя о действии для каждого конфликта.
        /// </summary>
        Ask = 0,

        /// <summary>
        /// Всегда оставлять версию с компьютера (Источник/Source).
        /// Файл на носителе будет перезаписан локальной версией.
        /// </summary>
        KeepLocal = 1,

        /// <summary>
        /// Всегда оставлять версию с носителя (Назначение/Dest).
        /// Локальный файл будет перезаписан версией с носителя (если это подразумевает тип синхронизации).
        /// </summary>
        KeepRemote = 2,

        /// <summary>
        /// Автоматически выбирать файл с более поздней датой изменения (LastWriteTimeUtc).
        /// </summary>
        KeepNewest = 3
    }
}
