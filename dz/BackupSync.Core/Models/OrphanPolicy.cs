namespace BackupSync.Core.Models
{
    /// <summary>
    /// Политика обработки "сирот".
    /// "Сирота" — это файл или папка, которая существует в Назначении (Dest/USB), но отсутствует в Источнике (Source/PC).
    /// Обычно это происходит, если файл был удален на компьютере.
    /// </summary>
    public enum OrphanPolicy
    {
        /// <summary>
        /// Спрашивать пользователя о действии для каждого найденного "сироты".
        /// </summary>
        Ask = 0,

        /// <summary>
        /// Ничего не делать (оставить файл на носителе).
        /// Файл будет проигнорирован и останется на диске, даже если его нет на компьютере.
        /// </summary>
        KeepOnRemote = 1,

        /// <summary>
        /// Автоматически удалить файл с носителя.
        /// Используется для режима "Зеркало" (Mirroring): если файл удален на ПК, он удаляется и на флешке.
        /// </summary>
        AutoDeleteOnRemote = 2,

        /// <summary>
        /// Автоматически скопировать файл обратно на компьютер.
        /// Используется в Двусторонней синхронизации: файл считается "новым", созданным на другом устройстве.
        /// </summary>
        AutoCopyToLocal = 3
    }
}
