namespace BackupSync.Core.Models
{
    /// <summary>
    /// Тип задания (режим синхронизации).
    /// Определяет направление передачи данных между Источником (PC) и Назначением (USB).
    /// </summary>
    public enum JobType
    {
        /// <summary>
        /// Одностороннее резервное копирование (Backup).
        /// Данные копируются строго из Источника в Назначение.
        /// Изменения на носителе не влияют на файлы на компьютере.
        /// </summary>
        OneWay = 1,

        /// <summary>
        /// Двусторонняя синхронизация (Sync).
        /// Данные синхронизируются в обоих направлениях.
        /// Актуальной считается версия с более поздней датой изменения.
        /// </summary>
        TwoWay = 2
    }
}
